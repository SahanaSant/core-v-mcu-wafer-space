# Write flow/build/sources.yaml: the design's file list as a LibreLane
# configuration fragment. Runs inside the toolchain container; `make harden`
# invokes it before LibreLane and passes the result as one of the config files.
#
# The file list is not maintained by hand anywhere in this repository. It comes
# from fusesoc resolving upstream's own unmodified `default` target, minus the
# eFPGA, plus rtl/gf180mcu, rtl/chip and the marker-cell black boxes; that is
# exactly what flow/synth/filelist.sh already builds for `make elaborate` and
# `make area`, so this script reuses it rather than describing the same list a
# second time in YAML that would then drift.
#
# Paths are written absolute, because LibreLane resolves `dir::` against the
# directory of the *last* config file on its command line and this one is
# generated into flow/build/ rather than flow/.

set -eu

. "${ROOT:-/foss/designs}/flow/synth/filelist.sh"

# Leaves the cwd at $WORK with gf180.f written there.
gf180_filelist

OUT=$BUILD/sources.yaml

{
    echo "# Generated by flow/synth/sources.sh. Do not edit; do not commit."
    echo "VERILOG_INCLUDE_DIRS:"
    sed -n 's|^+incdir+||p' gf180.f | while read -r dir; do
        case $dir in
            /*) printf -- '- %s\n' "$dir" ;;
            *)  printf -- '- %s\n' "$WORK/$dir" ;;
        esac
    done
    echo "VERILOG_FILES:"
    grep -v '^+incdir+' gf180.f | while read -r file; do
        case $file in
            /*) printf -- '- %s\n' "$file" ;;
            *)  printf -- '- %s\n' "$WORK/$file" ;;
        esac
    done
} >"$OUT"

echo "==> $(grep -c '^- ' "$OUT") source paths in flow/build/sources.yaml"
